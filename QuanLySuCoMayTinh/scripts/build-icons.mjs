import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import * as lucide from 'lucide';
import { iconGroups } from '../Client/icon-map.mjs';

const names = Object.keys(iconGroups);
for (const name of names) if (!lucide[name]) throw new Error(`Unknown Lucide icon: ${name}`);
const entries = Object.entries(iconGroups).flatMap(([name, aliases]) => aliases.split(' ').map(alias => `"bi-${alias}":${name}`));
// Generate named imports so unused Lucide icons never enter the browser bundle.
await writeFile('Client/system-icon-data.generated.js', `// Generated by npm run build:icons.\nimport { ${names.join(',')} } from 'lucide';\nexport const icons = {${entries.join(',')}};\n`);
await build({ entryPoints:['Client/system-icons.js'], outfile:'wwwroot/js/system-icons.bundle.js', bundle:true, minify:true, legalComments:'eof', target:['es2020'] });
